// Reads and writes the generated SHOTS block of shots.js (between "// <SHOTS>" and "// </SHOTS>"). Used by plan-shots.mjs and set-shots.mjs.
const q = (v) => JSON.stringify(v);
export const HEAD = '// <SHOTS> generated by scripts/plan-shots.mjs: it rewrites everything down to </SHOTS> and keeps the scenes you wrote\n// for lines of the narration that did not change.';

export function entryText(e) {
  const extra = [e.enter ? `enter: ${q(e.enter)}` : '', e.from ? `from: ${q(e.from)}` : '', e.crowd ? 'crowd: true' : '', e.file ? `file: ${q(e.file)}` : ''].filter(Boolean).join(', ');
  return `  { n: ${e.n}, word: ${e.word}, motion: ${q(e.motion || 'push')}, focus: ${q(e.focus || [0.5, 0.45])}${extra ? `, ${extra}` : ''},\n    says: ${q(e.says)},\n    who: ${q(e.who || [])}, shot: ${q(e.shot || 'medium shot')}, set: ${q(e.set || '')}, mood: ${q(e.mood || '')},\n    action: ${q(e.action)} },`;
}

export function replaceBlock(src, entries) {
  const a = src.indexOf('// <SHOTS>');
  const b = src.indexOf('// </SHOTS>');
  if (a < 0 || b < 0) throw new Error('shots.js has no "// <SHOTS>" ... "// </SHOTS>" block');
  return `${src.slice(0, a)}${HEAD}\nexport const SHOTS = [\n${entries.map(entryText).join('\n')}\n];\n// </SHOTS>${src.slice(b + '// </SHOTS>'.length)}`;
}
